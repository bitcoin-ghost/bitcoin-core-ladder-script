def vec_13_tagged_hash(node, wallet) -> dict:
    # BIP-340 tagged hash: conditions carry [HASH256(SHA256(tag)),
    # HASH256(expected)]. We pre-compute both because PREIMAGE auto-
    # conversion would only build the second slot, not the tag commit.
    tag = b"BIP0340/challenge"
    tag_hash = hashlib.sha256(tag).digest()
    preimage = b"\xab" * 16
    expected = hashlib.sha256(tag_hash + tag_hash + preimage).digest()
    rungs = [{
        "output_index": 0,
        "blocks": [{"type": "TAGGED_HASH", "fields": [
            {"type": "HASH256", "hex": tag_hash.hex()},
            {"type": "HASH256", "hex": expected.hex()},
        ]}],
    }]
    fb = _fund_and_capture(node, wallet, rungs, "vec13")
    return {
        "id": 13,
        "name": "TAGGED_HASH BIP-340 (Reveal P)",
        "witness_rule": "Reveal P",
        "block_types": ["TAGGED_HASH"],
        "tag_utf8": tag.decode(),
        "tag_hash_hex": tag_hash.hex(),
        "preimage_hex": preimage.hex(),
        "expected_hex": expected.hex(),
        "fund_tx": _shape_fund(fb),
    }


