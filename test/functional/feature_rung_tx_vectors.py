def _fund_and_capture(node, wallet, rungs: list, label: str):
    """Drive a baseline fund tx via createrungtx + wallet sign;
    return the {fund_tx, mlsc_value_btc, conditions_root, spk}
    bundle."""
    utxo = wallet.get_utxo()
    amt = (Decimal(str(utxo["value"])) - Decimal("0.001")).quantize(Decimal("0.00000001"))
    result = node.createrungtx(
        [{"txid": utxo["txid"], "vout": utxo["vout"]}],
        [amt],
        rungs,
    )
    tx = tx_from_hex(result["hex"])
    wallet.sign_tx(tx)
    signed_hex = tx.serialize().hex()
    txid = node.sendrawtransaction(signed_hex)
    return {
        "fund_txid": txid,
        "fund_hex": signed_hex,
        "fund_size_bytes": len(signed_hex) // 2,
        "mlsc_scriptpubkey": result["scriptPubKey"],
        "mlsc_value_btc": float(amt),
        # `conditions_root` is what's on the wire — for single-SIG-rung
        # txs this is the BIP-341-style tweaked root (key_path=true).
        # `merkle_root` is the untweaked TX_MLSC root, exposed so an
        # independent verifier can validate leaf+tree logic separately
        # from the tweak step (which is just BIP-341 with a "LadderTweak/
        # v1" tag).
        "merkle_root": result.get("merkle_root"),
        "conditions_root": result["conditions_root"],
        "key_path": result.get("key_path", False),
        "internal_pubkey": result.get("internal_pubkey"),
    }


