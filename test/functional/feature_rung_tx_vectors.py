def vec_15_accumulator(node, wallet) -> dict:
    # ACCUMULATOR conditions hold the Merkle root of the membership set;
    # spend reveals one leaf + Merkle proof in the witness. Vector here
    # only documents the fund-time wire shape.
    leaves = [hashlib.sha256(f"acc-leaf-{i}".encode()).digest() for i in range(4)]
    # Simple 4-leaf Merkle root with double-SHA256 internal nodes.
    def _merkle(level):
        while len(level) > 1:
            if len(level) % 2 == 1:
                level.append(level[-1])
            level = [hashlib.sha256(hashlib.sha256(level[i] + level[i+1]).digest()).digest()
                     for i in range(0, len(level), 2)]
        return level[0]
    root = _merkle(list(leaves))
    rungs = [{
        "output_index": 0,
        "blocks": [{"type": "ACCUMULATOR", "fields": [
            {"type": "HASH256", "hex": root.hex()},
        ]}],
    }]
    fb = _fund_and_capture(node, wallet, rungs, "vec15")
    return {
        "id": 15,
        "name": "ACCUMULATOR Merkle membership root",
        "witness_rule": "Accumulator",
        "block_types": ["ACCUMULATOR"],
        "leaves_hex": [l.hex() for l in leaves],
        "merkle_root_hex": root.hex(),
        "fund_tx": _shape_fund(fb),
    }


