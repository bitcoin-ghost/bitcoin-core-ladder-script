REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT_PATH = REPO_ROOT / "src" / "test" / "data" / "rung_tx_vectors.json"


def derive_key(seed: str) -> ECKey:
    """Deterministic ECKey from seed string. SHA-256 the seed; tweak the
    last byte if (extremely unlikely) it lands on the curve order or
    zero."""
    h = hashlib.sha256(seed.encode()).digest()
    if h == b"\x00" * 32:
        h = b"\x01" * 32
    k = ECKey()
    k.set(h, True)
    return k


def schnorr_pk_compressed(k: ECKey) -> bytes:
    return k.get_pubkey().get_bytes()


def write_or_verify_vectors(vectors: list, source_description: str):
    """Default behaviour is VERIFY: compare regenerated bytes to the
    committed fixture and fail on drift. With `VECTORS_REGENERATE=1`
    in the environment, overwrite the committed fixture instead.

    This is the CI-load-bearing path: any consensus change that would
    invalidate a vector causes `make check` to fail with a clear diff."""
    payload = {
        "version": 1,
        "description": source_description,
        "vectors": vectors,
    }
    new_text = json.dumps(payload, indent=2) + "\n"
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)

    if os.environ.get("VECTORS_REGENERATE") == "1":
        tmp = OUTPUT_PATH.with_suffix(".json.tmp")
        tmp.write_text(new_text)
        tmp.replace(OUTPUT_PATH)
        print(f"wrote {len(vectors)} vectors -> {OUTPUT_PATH}")
        return

    # Verify mode (default).
    if not OUTPUT_PATH.exists():
        raise AssertionError(
            f"{OUTPUT_PATH} does not exist; "
            f"run with VECTORS_REGENERATE=1 to create it"
        )
    existing_text = OUTPUT_PATH.read_text()
    if existing_text == new_text:
        print(f"verified {len(vectors)} vectors == {OUTPUT_PATH.name}")
        return

    # Drift — produce a useful diff hint and fail.
    import difflib
    diff_lines = list(difflib.unified_diff(
        existing_text.splitlines(), new_text.splitlines(),
        fromfile=f"committed/{OUTPUT_PATH.name}",
        tofile="regenerated",
        n=2,
        lineterm="",
    ))
    diff = "\n".join(diff_lines[:80])
    raise AssertionError(
        f"FIXTURE DRIFT in {OUTPUT_PATH.name}: regenerated bytes "
        f"differ from committed file. If this is intentional, "
        f"re-run with VECTORS_REGENERATE=1.\n\n{diff}\n"
        f"(diff truncated; first 80 lines)"
    )


# Backward-compat alias — older code paths may still call write_vectors.
write_vectors = write_or_verify_vectors


