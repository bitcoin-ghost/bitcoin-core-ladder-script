def vec_8_pq_batch_anchor(node, wallet) -> dict:
    # Probe liboqs availability.
    try:
        kp = node.generatepqkeypair("FALCON512")
    except Exception as e:
        if "liboqs" in str(e).lower():
            return None  # skip — not a hard requirement for the fixture
        raise
    pubkey_hex = kp["pubkey"]
    commit_hex = hashlib.sha256(bytes.fromhex(pubkey_hex)).hexdigest()
    rungs = [{
        "output_index": 0,
        "blocks": [{"type": "PQ_BATCH", "fields": [
            {"type": "HASH256", "hex": commit_hex},
        ]}],
    }]
    fb = _fund_and_capture(node, wallet, rungs, "vec8")
    return {
        "id": 8,
        "name": "PQ_BATCH single-anchor input (FALCON-512)",
        "witness_rule": "PQ-anchor",
        "block_types": ["PQ_BATCH"],
        "falcon_pubkey_size_bytes": len(pubkey_hex) // 2,
        "commit_sha256_hex": commit_hex,
        "fund_tx": _shape_fund(fb),
    }


def vec_9_data_return(node, wallet) -> dict:
    # DATA_RETURN: 8-byte nValue == 0 + payload up to 40 bytes on the
    # wire. createrungtx accepts the data field directly.
    payload = b"vec9-data-return-fixture-test"
    assert len(payload) <= 40
    rungs = [{
        "output_index": 0,
        "blocks": [{"type": "DATA_RETURN", "fields": [
            {"type": "DATA", "hex": payload.hex()},
        ]}],
    }]
    # DATA_RETURN funds with nValue = 0 — we need ONE non-DATA_RETURN
    # output (any v4 output) to satisfy the per-tx "every output has at
    # least one rung" check. Use a SIG rung at output_index=1 that
    # carries a single-block SIG with a placeholder pubkey.
    placeholder_pk = derive_key("bip-xxxx-vec9-placeholder").get_pubkey().get_bytes().hex()
    rungs.append({
        "output_index": 1,
        "blocks": [{"type": "SIG", "fields": [
            {"type": "SCHEME", "hex": "01"},
            {"type": "PUBKEY", "hex": placeholder_pk},
        ]}],
    })
    utxo = wallet.get_utxo()
    spendable_amt = (Decimal(str(utxo["value"])) - Decimal("0.002")).quantize(Decimal("0.00000001"))
    result = node.createrungtx(
        [{"txid": utxo["txid"], "vout": utxo["vout"]}],
        [Decimal("0.00000000"), spendable_amt],
        rungs,
    )
    tx = tx_from_hex(result["hex"])
    wallet.sign_tx(tx)
    signed_hex = tx.serialize().hex()
    txid = node.sendrawtransaction(signed_hex)
    return {
        "id": 9,
        "name": "DATA_RETURN payload + SIG vout (Unspendable witness rule)",
        "witness_rule": "Unspendable",
        "block_types": ["DATA_RETURN", "SIG"],
        "data_return_payload_hex": payload.hex(),
        "data_return_payload_len": len(payload),
        "fund_tx": {
            "txid": txid,
            "hex": signed_hex,
            "size_bytes": len(signed_hex) // 2,
            "mlsc_scriptpubkey": result["scriptPubKey"],
            "conditions_root": result["conditions_root"],
            "vouts": 2,
        },
    }


def _shape_fund(fb: dict) -> dict:
    """Convert _fund_and_capture's bundle to the spec's fund_tx schema."""
    out = {
        "txid": fb["fund_txid"],
        "hex": fb["fund_hex"],
        "size_bytes": fb["fund_size_bytes"],
        "mlsc_scriptpubkey": fb["mlsc_scriptpubkey"],
        "mlsc_value_btc": fb["mlsc_value_btc"],
        "conditions_root": fb["conditions_root"],
        "key_path": fb["key_path"],
    }
    if fb.get("internal_pubkey"):
        out["internal_pubkey"] = fb["internal_pubkey"]
    return out


