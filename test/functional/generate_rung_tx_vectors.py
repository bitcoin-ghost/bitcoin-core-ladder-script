def vec_6_multisig_2of3(node, wallet) -> dict:
    seeds = ["bip-xxxx-vec6-msig-a", "bip-xxxx-vec6-msig-b", "bip-xxxx-vec6-msig-c"]
    pks = [derive_key(s) for s in seeds]
    pk_hexes = [schnorr_pk_compressed(k).hex() for k in pks]
    # createrungtx for MULTISIG takes the full pubkey list and computes
    # the inner-Merkle pubkey root commit itself (post-E-018a).
    rungs = [{
        "output_index": 0,
        "blocks": [{"type": "MULTISIG", "fields": [
            {"type": "NUMERIC", "hex": "02000000"},   # K = 2
            {"type": "SCHEME",  "hex": "01"},          # SCHNORR
            {"type": "PUBKEY",  "hex": pk_hexes[0]},   # canonical sort
            {"type": "PUBKEY",  "hex": pk_hexes[1]},
            {"type": "PUBKEY",  "hex": pk_hexes[2]},
        ]}],
    }]
    fb = _fund_and_capture(node, wallet, rungs, "vec6")
    return {
        "id": 6,
        "name": "MULTISIG 2-of-3 with inner-Merkle pubkey commit",
        "witness_rule": "Triplets K",
        "block_types": ["MULTISIG"],
        "key_seeds": {f"k{i}": s for i, s in enumerate(seeds)},
        "pubkeys_compressed": pk_hexes,
        "threshold": 2,
        "fund_tx": _shape_fund(fb),
    }


