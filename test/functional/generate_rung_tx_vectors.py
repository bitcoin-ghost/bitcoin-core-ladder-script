"""Generate src/test/data/rung_tx_vectors.json — reproducible v4 RUNG_TX
fund+spend reference vectors covering all eight witness-rule families
(Fixed N, Empty, Reveal P, Triplets K, Accumulator, Bridging,
PQ-anchor, Unspendable).

Run:
    python3 test/functional/generate_rung_tx_vectors.py

Each vector is generated by funding an MLSC output via createrungtx
(MiniWallet supplies the input + signs the bootstrap), then spending
the MLSC output via signrungtx where applicable. Key material is
derived deterministically from a seed string (SHA-256(seed)) so re-runs
produce byte-identical vectors.

This is the activation-gate-component-3 generator. The current set is
the seed for expansion toward the 50+ vector bar (positive + negative
+ edge cases per rule family).

The script writes to a temp file then renames over
src/test/data/rung_tx_vectors.json so partially-generated runs can't
corrupt the committed fixture.
"""

