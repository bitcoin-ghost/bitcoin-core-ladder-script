class GenerateRungTxVectors(BitcoinTestFramework):
    def set_test_params(self):
        self.num_nodes = 1
        self.setup_clean_chain = True
        self.noban_tx_relay = True

    def run_test(self):
        node = self.nodes[0]
        wallet = MiniWallet(node)
        self.generate(wallet, COINBASE_MATURITY + 20)

        builders = [
            vec_1_sig_keypath,
            vec_2_p2wpkh_legacy,
            vec_3_htlc,
            vec_4_csv,
            vec_5_cltv,
            vec_6_multisig_2of3,
            vec_7_ctv,
            vec_8_pq_batch_anchor,
            vec_9_data_return,
        ]
        vectors = []
        for builder in builders:
            try:
                v = builder(node, wallet)
                if v is None:
                    self.log.info(f"  {builder.__name__}: skipped")
                    continue
                vectors.append(v)
                self.generate(node, 1)
                self.log.info(f"  {builder.__name__}: ok (id {v['id']})")
            except Exception as e:
                self.log.error(f"  {builder.__name__}: FAILED — {e}")
                raise

        write_vectors(
            vectors,
            "Reproducible v4 RUNG_TX fund (and where applicable spend) "
            "transaction vectors. Generated by "
            "test/functional/generate_rung_tx_vectors.py — re-run to "
            "regenerate. Covers the eight witness-rule families: "
            "Fixed N (vec 1), Bridging (vec 2), Reveal P + Triplets K "
            "(vec 3), Empty (vec 4, 5, 7), Triplets K (vec 6), "
            "PQ-anchor (vec 8), Unspendable (vec 9). Negative vectors "
            "and remaining rules (Accumulator, more Bridging variants) "
            "tracked in test/functional/feature_rung_anti_embedding.py "
            "and to be appended in subsequent passes toward the "
            "activation gate's 50+ vector bar.",
        )

        self.log.info(f"Generated {len(vectors)} vectors → {OUTPUT_PATH}")


if __name__ == "__main__":
    GenerateRungTxVectors(__file__).main()
