def vec_1_sig_keypath(node, wallet) -> dict:
    seed_fund = "bip-xxxx-vec1-fund-key"
    seed_sweep = "bip-xxxx-vec1-sweep-key"
    fund_pk = derive_key(seed_fund)
    sweep_pk = derive_key(seed_sweep)
    fund_pk_hex = schnorr_pk_compressed(fund_pk).hex()
    sweep_pk_hex = schnorr_pk_compressed(sweep_pk).hex()
    rungs = [{
        "output_index": 0,
        "blocks": [{"type": "SIG", "fields": [
            {"type": "SCHEME", "hex": "01"},
            {"type": "PUBKEY", "hex": fund_pk_hex},
        ]}],
    }]
    fb = _fund_and_capture(node, wallet, rungs, "vec1")
    return {
        "id": 1,
        "name": "SIG single-rung Schnorr key-path",
        "witness_rule": "Fixed N + key-path tweak",
        "block_types": ["SIG"],
        "key_seeds": {"fund": seed_fund, "sweep": seed_sweep},
        "fund_pubkey_compressed": fund_pk_hex,
        "sweep_pubkey_compressed": sweep_pk_hex,
        "fund_tx": _shape_fund(fb),
    }


def vec_2_p2wpkh_legacy(node, wallet) -> dict:
    seed_p2wpkh = "bip-xxxx-vec2-p2wpkh-key"
    pk = derive_key(seed_p2wpkh)
    pk_hex = schnorr_pk_compressed(pk).hex()
    # P2WPKH_LEGACY conditions take PUBKEY in the spec; createrungtx
    # computes HASH160 itself.
    rungs = [{
        "output_index": 0,
        "blocks": [{"type": "P2WPKH_LEGACY", "fields": [
            {"type": "PUBKEY", "hex": pk_hex},
        ]}],
    }]
    fb = _fund_and_capture(node, wallet, rungs, "vec2")
    return {
        "id": 2,
        "name": "P2WPKH_LEGACY wrapper (HASH160-committed pubkey)",
        "witness_rule": "Bridging (legacy P2*)",
        "block_types": ["P2WPKH_LEGACY"],
        "key_seeds": {"p2wpkh": seed_p2wpkh},
        "p2wpkh_pubkey_compressed": pk_hex,
        "fund_tx": _shape_fund(fb),
    }


def vec_3_htlc(node, wallet) -> dict:
    seed_recv = "bip-xxxx-vec3-htlc-recv"
    seed_send = "bip-xxxx-vec3-htlc-send"
    recv_pk = derive_key(seed_recv)
    send_pk = derive_key(seed_send)
    recv_pk_hex = schnorr_pk_compressed(recv_pk).hex()
    send_pk_hex = schnorr_pk_compressed(send_pk).hex()
    preimage = b"\x42" * 32
    payment_hash = hashlib.sha256(preimage).digest()
    # HTLC conditions: [HASH256, NUMERIC(csv), SCHEME] — createrungtx
    # accepts HASH256 directly here (it's an external commitment, not
    # auto-derived from PREIMAGE for HTLC's claim path).
    rungs = [{
        "output_index": 0,
        "blocks": [{"type": "HTLC", "fields": [
            {"type": "PREIMAGE", "hex": preimage.hex()},  # createrungtx will compute HASH256
            {"type": "NUMERIC",  "hex": "90000000"},     # CSV = 144 (LE)
            {"type": "SCHEME",   "hex": "01"},
            {"type": "PUBKEY",   "hex": recv_pk_hex},
            {"type": "PUBKEY",   "hex": send_pk_hex},
        ]}],
    }]
    fb = _fund_and_capture(node, wallet, rungs, "vec3")
    return {
        "id": 3,
        "name": "HTLC (claim path: preimage + sig)",
        "witness_rule": "Fixed 5 (Triplets K + Reveal P)",
        "block_types": ["HTLC"],
        "key_seeds": {"recv": seed_recv, "send": seed_send},
        "recv_pubkey_compressed": recv_pk_hex,
        "send_pubkey_compressed": send_pk_hex,
        "preimage_hex": preimage.hex(),
        "payment_hash_hex": payment_hash.hex(),
        "csv_blocks": 144,
        "fund_tx": _shape_fund(fb),
    }


